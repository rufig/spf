\ Opt-in IPv4 LAN discovery on the existing DTLS socket; one network owner.
\ A beacon is only an address hint. Never bypass mutual DTLS or application ACLs.
REQUIRE SWARM-DTLS-SERVE ~ac/lib/net/dtls-net.f
48 CONSTANT /SWARM-LAN
CREATE LAN-TX /SWARM-LAN ALLOT
CREATE LAN-OPT 4 ALLOT
VARIABLE LAN-NEXT VARIABLE LAN-DIAL-DUE VARIABLE LAN-ENABLED
VARIABLE LAN-PORT
VARIABLE LAN-SENT VARIABLE LAN-RECEIVED
0 VALUE LAN-CANDIDATE-XT \ ( ip port expected-SPKI -- ); borrowed key during callback
15000 VALUE LAN-INTERVAL
: LAN-PRIVATE? { ip -- flag }
  ip 255 AND 10 = IF TRUE EXIT THEN
  ip 65535 AND 43200 = IF TRUE EXIT THEN \ 192.168
  ip 65535 AND 65193 = IF TRUE EXIT THEN \ 169.254
  ip 255 AND 172 = ip 8 RSHIFT 255 AND 16 32 WITHIN AND
;
REQUIRE LAN-REFRESH ~ac/lib/net/lan-interfaces.f
: LAN-RX { n ip port \ key -- consumed }
  n /SWARM-LAN <> IF FALSE EXIT THEN
  RXBIG 8 S" ACSWLAN1" COMPARE IF FALSE EXIT THEN
  LAN-ENABLED @ 0= IF TRUE EXIT THEN
  RXBIG 8 + IH-GROUP 20 MEM= 0= IF TRUE EXIT THEN
  RXBIG 28 + -> key
  key IH-SELF 20 MEM= IF TRUE EXIT THEN
  1 LAN-RECEIVED +!
  ip LAN-PRIVATE? port 1 65536 WITHIN AND 0= IF TRUE EXIT THEN
  \ A deterministic initiator avoids two ClientHellos colliding on one endpoint.
  IH-SELF 20 key 20 COMPARE 0< 0= IF TRUE EXIT THEN
  NOW-MS LAN-DIAL-DUE @ - 0< IF TRUE EXIT THEN
  NOW-MS 250 + LAN-DIAL-DUE !
  LAN-CANDIDATE-XT IF ip port key LAN-CANDIDATE-XT EXECUTE THEN TRUE
;
: LAN-OPEN { port -- }
  SWARM-LOCAL-RX-XT IF -3301 THROW THEN
  port 1 65536 WITHIN 0= IF -3301 THROW THEN
  1 LAN-OPT L!
  [DEFINED] WINAPI: [IF]
    4 LAN-OPT SO_BROADCAST SOL_SOCKET DHT-SOCK @ setsockopt
  [ELSE]
    [DEFINED] DLFN: [IF]
    4 LAN-OPT 32 65535 DHT-SOCK @ (u-setsockopt)
    [ELSE]
    4 LAN-OPT 6 1 DHT-SOCK @ (u-setsockopt)
    [THEN]
  [THEN]
  0<> IF -3301 THROW THEN
  port LAN-PORT !
  S" ACSWLAN1" LAN-TX SWAP MOVE
  IH-GROUP LAN-TX 8 + 20 MOVE IH-SELF LAN-TX 28 + 20 MOVE
  NOW-MS DUP LAN-NEXT ! LAN-DIAL-DUE !
  TRUE LAN-ENABLED ! ['] LAN-RX TO SWARM-LOCAL-RX-XT
  0 LAN-SENT ! 0 LAN-RECEIVED !
  ." discovery: automatic LAN subnet broadcasts" CR
;
: LAN-BROADCAST { \ p -- }
  LAN-TARGETS @ -> p
  BEGIN p WHILE
    p li.ip @ LAN-PORT @ LAN-TX /SWARM-LAN DHT-SOCK @ UDP-SEND
    1 LAN-SENT +! p li.next @ -> p
  REPEAT
;
: LAN-TICK ( -- )
  LAN-ENABLED @ 0= IF EXIT THEN
  NOW-MS LAN-NEXT @ - 0< IF EXIT THEN
  NOW-MS LAN-INTERVAL + RND 1023 AND + LAN-NEXT !
  ['] LAN-REFRESH CATCH ?DUP IF
    ." discovery: interface enumeration failed ior=" . CR LAN-TARGETS-FREE EXIT
  THEN
  LAN-BROADCAST
;
: LAN-CLOSE ( -- )
  FALSE LAN-ENABLED ! 0 TO LAN-CANDIDATE-XT
  LAN-TARGETS-FREE
  SWARM-LOCAL-RX-XT ['] LAN-RX = IF 0 TO SWARM-LOCAL-RX-XT THEN
;
